#[test]
#[cfg_attr(
    miri,
    ignore = "reads the repository from disk; Miri has no filesystem"
)]
fn the_public_surface_is_what_was_agreed() {
    let root = repo_root();
    let found = scan_crate(&root);

    // A scanner that returned nothing would agree with an empty snapshot. These
    // are the anchors: if they are missing the scan is broken, whatever the
    // snapshot says.
    for anchor in [
        "use heapscope::Profiler = profiler::Profiler",
        "mod heapscope::stats",
        "macro heapscope::assert_max_bytes",
        "struct heapscope::stats::HeapStats",
    ] {
        assert!(
            found.contains(anchor),
            "the scan did not find `{anchor}`, so it is not reading the crate"
        );
    }
    // A hidden module may be *named* — the source path of a re-export is part
    // of what is recorded — but nothing may be reachable *at* a path inside one.
    let leaked: Vec<&String> = found
        .iter()
        .filter(|item| item.contains("heapscope::internals") || item.contains("heapscope::unwind"))
        .filter(|item| !item.starts_with("use "))
        .collect();
    assert!(
        leaked.is_empty(),
        "a `#[doc(hidden)]` module was walked into; it is not supported surface: {leaked:?}"
    );

    let path = root.join(SNAPSHOT);
    let committed = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "cannot read {SNAPSHOT}: {e}\n\
             If it does not exist yet, write it with:\n  \
             cargo test --test public_surface -- --ignored --exact rewrite_the_snapshot"
        )
    });
    let expected: BTreeSet<String> = committed
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.trim_start().starts_with('#'))
        .map(str::to_string)
        .collect();

    let added: Vec<&String> = found.difference(&expected).collect();
    let removed: Vec<&String> = expected.difference(&found).collect();

    if added.is_empty() && removed.is_empty() {
        return;
    }

    let mut message = String::from("the public surface is not what `");
    let _ = write!(message, "{SNAPSHOT}` says it is.\n\n");
    if !added.is_empty() {
        message.push_str("added (not previously promised):\n");
        for item in &added {
            let _ = writeln!(message, "  + {item}");
        }
    }
    if !removed.is_empty() {
        message.push_str("removed (previously promised):\n");
        for item in &removed {
            let _ = writeln!(message, "  - {item}");
        }
    }
    message.push_str(
        "\nIf every line above is a change somebody decided to make, record it with:\n  \
         cargo test --test public_surface -- --ignored --exact rewrite_the_snapshot\n",
    );
    panic!("{message}");
}

/// Rewrites the committed surface. Ignored by default: it is a tool, not a
/// check, and a check that repairs itself checks nothing.
#[test]
#[ignore = "rewrites tests/data/public_surface.txt; run it deliberately"]
#[cfg_attr(miri, ignore = "writes to the repository; Miri has no filesystem")]
fn rewrite_the_snapshot() {
    let root = repo_root();
    let surface = scan_crate(&root);
    let path = root.join(SNAPSHOT);
    std::fs::write(&path, render(&surface))
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
    println!("wrote {} items to {SNAPSHOT}", surface.len());
}
