//! The supported public surface, written down and compared against the source.
//!
//! `#[doc(hidden)]` marks `internals` and `unwind` as unsupported, but it is a
//! convention rather than an enforcement: it hides a module from the rendered
//! documentation and stops nobody from depending on it. The risk that actually
//! needs a mechanism is the other one — the *supported* surface growing by
//! accident, one convenient `pub` at a time, until a thing nobody decided to
//! promise is a thing that cannot be changed before 1.0.
//!
//! So the surface is a committed file. Adding to it is one line in a diff and a
//! reviewer's decision; adding to it without noticing is a failing test.
//!
//! # What this covers, and what it does not
//!
//! Covered: every public module reachable from the crate root without passing
//! through a `#[doc(hidden)]` one, and within those modules every public item,
//! struct field, enum variant, inherent `pub fn` and `pub const`, trait
//! implementation (written or derived), `#[non_exhaustive]` marker, re-export
//! *with the path it re-exports*, and `#[macro_export]` macro.
//!
//! Not covered: anything a scan of the source cannot see. Trait implementations
//! generated by a macro, blanket implementations, and auto-traits (`Send`,
//! `Sync`, `Unpin`) are absent, so this does not catch a private field change
//! that makes a public type `!Send`. That is a real gap and the reason this is a
//! tripwire rather than a proof.
//!
//! # Updating it
//!
//! `cargo test --test public_surface -- --ignored --exact rewrite_the_snapshot`
//! rewrites the file, and the change then shows up in review as itself.
//!
//! It is deliberately not an environment variable. The variable that turns a
//! gate into a recorder is the one that gets read wrong — `HEAPSCOPE_UPDATE_BASELINE`
//! spent a chunk being read as *on* when set to `FALSE` — and a rule with no
//! spellings has no spelling to get wrong.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

// Every test here reads the repository from disk, which Miri turns into a hard
// machine abort rather than an `io::Error`. Same treatment as
// `tests/no_dependencies.rs`, and for the same reason.

/// Where the committed surface lives.
const SNAPSHOT: &str = "tests/data/public_surface.txt";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

